// Theme Switcher Logic
const themeToggle = document.getElementById('themeToggle');
const currentTheme = localStorage.getItem('theme') || 'light';

// Set initial theme
if (currentTheme === 'dark') {
    document.documentElement.setAttribute('data-theme', 'dark');
} else {
    document.documentElement.setAttribute('data-theme', 'light');
}

if (themeToggle) {
    themeToggle.addEventListener('click', () => {
        let theme = document.documentElement.getAttribute('data-theme');
        if (theme === 'dark') {
            document.documentElement.setAttribute('data-theme', 'light');
            localStorage.setItem('theme', 'light');
        } else {
            document.documentElement.setAttribute('data-theme', 'dark');
            localStorage.setItem('theme', 'dark');
        }
    });
}

// Render Articles Grid
const articlesGrid = document.getElementById('articlesGrid');
const noResults = document.getElementById('noResults');

function displayArticles(articles) {
    if (!articlesGrid) return;
    
    if (articles.length === 0) {
        articlesGrid.innerHTML = '';
        if (noResults) noResults.classList.remove('hidden');
        return;
    }
    
    if (noResults) noResults.classList.add('hidden');
    
    articlesGrid.innerHTML = articles.map(article => `
        <div class="article-card" onclick="openArticle(${article.id})">
            <div>
                <div class="card-tag">${article.category}</div>
                <h3 class="card-title">${article.title}</h3>
                <p class="card-excerpt">${article.excerpt}</p>
            </div>
            <div class="card-footer">
                <span class="card-author">${article.author}</span>
                <span class="card-date">${article.date}</span>
            </div>
        </div>
    `).join('');
}

// Search Logic
const searchInput = document.getElementById('searchInput');

if (searchInput) {
    searchInput.addEventListener('input', (e) => {
        const query = e.target.value.toLowerCase().trim();
        
        const filteredArticles = articlesData.filter(article => {
            return article.title.toLowerCase().includes(query) ||
                   article.category.toLowerCase().includes(query) ||
                   article.excerpt.toLowerCase().includes(query) ||
                   article.author.toLowerCase().includes(query);
        });
        
        displayArticles(filteredArticles);
    });
}

// Modal Interaction Logic
const modal = document.getElementById('articleModal');
const modalClose = document.getElementById('modalClose');

// Expose openArticle globally so inline onclick works
window.openArticle = function(id) {
    if (!modal) return;
    
    const article = articlesData.find(a => a.id === id);
    if (!article) return;

    document.getElementById('modalCategory').innerText = article.category;
    document.getElementById('modalDate').innerText = article.date;
    document.getElementById('modalTitle').innerText = article.title;
    document.getElementById('modalAuthor').innerText = `By ${article.author}`;
    document.getElementById('modalBody').innerHTML = article.content;

    modal.classList.add('active');
    document.body.style.overflow = 'hidden'; // Lock background scroll
}

if (modalClose) {
    modalClose.addEventListener('click', () => {
        modal.classList.remove('active');
        document.body.style.overflow = ''; // Unlock background scroll
    });
}

if (modal) {
    modal.addEventListener('click', (e) => {
        if (e.target === modal) {
            modal.classList.remove('active');
            document.body.style.overflow = '';
        }
    });
    
    // Allow Escape key to close modal
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && modal.classList.contains('active')) {
            modal.classList.remove('active');
            document.body.style.overflow = '';
        }
    });
}

// Initialize on Load
document.addEventListener('DOMContentLoaded', () => {
    displayArticles(articlesData);
});
